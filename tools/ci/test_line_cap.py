"""Tests for tools/ci/line_cap.py: the allowlist rules, parsing, and the git-tracked tree on a tmp repo."""

from __future__ import annotations

import subprocess
from pathlib import Path

import line_cap
import pytest

CAP = 10


def allow(legacy: dict[str, int] | None = None, exempt: dict[str, str] | None = None) -> line_cap.Allowlist:
    return line_cap.Allowlist(legacy or {}, exempt or {})


@pytest.mark.unit
def test_files_at_or_under_the_cap_pass() -> None:
    assert line_cap.check({"a.py": 10, "b.lua": 3}, allow(), cap=CAP) == []


@pytest.mark.unit
def test_new_file_over_the_cap_fails() -> None:
    assert line_cap.check({"a.py": 11}, allow(), cap=CAP) == ["a.py: 11 lines, over the 10-line cap: split it"]


@pytest.mark.unit
def test_listed_file_at_its_length_passes() -> None:
    assert line_cap.check({"a.py": 50}, allow({"a.py": 50}), cap=CAP) == []


@pytest.mark.unit
def test_listed_file_that_grew_fails() -> None:
    assert line_cap.check({"a.py": 51}, allow({"a.py": 50}), cap=CAP) == [
        "a.py: grew from 50 to 51 lines: listed files may only shrink"
    ]


@pytest.mark.unit
def test_listed_file_that_shrank_must_lower_its_entry() -> None:
    assert line_cap.check({"a.py": 40}, allow({"a.py": 50}), cap=CAP) == [
        "a.py: shrank from 50 to 40 lines: lower its allowlist entry to 40"
    ]


@pytest.mark.unit
def test_listed_file_below_the_cap_must_leave_the_list() -> None:
    assert line_cap.check({"a.py": 10}, allow({"a.py": 50}), cap=CAP) == [
        "a.py: 10 lines, at or below the cap now: remove it from the allowlist"
    ]


@pytest.mark.unit
def test_listed_file_that_is_gone_must_leave_the_list() -> None:
    problems = line_cap.check({}, allow({"a.py": 50}, {"d.lua": "data"}), cap=CAP)
    assert problems == [
        "a.py: listed but not a tracked capped file: remove it from the allowlist",
        "d.lua: listed but not a tracked capped file: remove it from the allowlist",
    ]


@pytest.mark.unit
def test_exempt_file_has_no_cap() -> None:
    assert line_cap.check({"d.lua": 5000}, allow(exempt={"d.lua": "generated table"}), cap=CAP) == []


@pytest.mark.unit
def test_parse_allowlist() -> None:
    parsed = line_cap.parse_allowlist("# header\n\n1200 a.py\nexempt d.lua  # generated by gen.py\n")
    assert parsed == allow({"a.py": 1200}, {"d.lua": "generated by gen.py"})


@pytest.mark.unit
@pytest.mark.parametrize(
    ("text", "error"),
    [
        ("exempt d.lua\n", "needs a reason"),
        ("1200 a.py\n1100 a.py\n", "listed twice"),
        ("big a.py\n", "a line count or 'exempt'"),
        ("1200 a.py extra\n", "expected '<lines> <path>'"),
    ],
)
def test_parse_allowlist_refuses(text: str, error: str) -> None:
    with pytest.raises(ValueError, match=error):
        line_cap.parse_allowlist(text)


@pytest.mark.unit
def test_count_lines() -> None:
    assert line_cap.count_lines(b"") == 0
    assert line_cap.count_lines(b"a\nb\n") == 2
    assert line_cap.count_lines(b"a\nb") == 2


@pytest.mark.integration
def test_tracked_lengths_reads_only_tracked_capped_files(tmp_path: Path) -> None:
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
    (tmp_path / "sub").mkdir()
    (tmp_path / "sub" / "a.py").write_text("x\n" * 3)
    (tmp_path / "b.sh").write_text("echo\n")
    (tmp_path / "notes.md").write_text("text\n" * 2000)
    (tmp_path / "untracked.py").write_text("x\n" * 2000)
    subprocess.run(["git", "add", "sub/a.py", "b.sh", "notes.md"], cwd=tmp_path, check=True)
    assert line_cap.tracked_lengths(tmp_path) == {"sub/a.py": 3, "b.sh": 1}


@pytest.mark.integration
def test_the_repo_allowlist_parses() -> None:
    parsed = line_cap.parse_allowlist(line_cap.ALLOWLIST.read_text())
    assert all(n > line_cap.CAP for n in parsed.legacy.values())
