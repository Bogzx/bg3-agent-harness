"""Build mod/.../Server/Data/JournalMarkers.lua from extracted Story/Journal files.

The game ships one Story/Journal/Markers/<guid>.lsx per map marker (marker id ->
target object uuid, display text handle) and objective_prototypes.lsx (objective ->
marker ids). Ext.IO can't list directories, so the marker files are indexed offline.
Quest steps -> objectives are parsed at runtime from quest_prototypes.lsx.

usage: python3 -I gen_marker_index.py <extracted_journal_dir> <out.lua>
"""
import glob
import re
import sys


def attr(s, name):
    m = re.search(r'id="%s" type="[^"]*" (?:value|handle)="([^"]*)"' % re.escape(name), s)
    return m.group(1) if m else ""


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(src, out):
    markers = {}
    for f in sorted(glob.glob(src + "/*Story__Journal__Markers__*.lsx")):
        s = open(f, encoding="utf-8").read()
        for node in re.findall(r'<node id="Marker">(.*?)</node>', s, re.S):
            mid = attr(node, "MarkerID")
            if mid:
                markers[mid] = {
                    "type": attr(node, "MarkerTargetObjectType"),
                    "uuid": attr(node, "MarkerTargetObjectUUID"),
                    "text": attr(node, "DisplayText"),
                    "level": attr(node, "MarkerLevel"),
                    "icon": attr(node, "MarkerIcon"),
                    "radius": attr(node, "Radius") or "0",
                }
    objectives = {}
    obj_src = glob.glob(src + "/*objective_prototypes.lsx")[0]
    s = open(obj_src, encoding="utf-8").read()
    for node in re.split(r'<node id="Objective">', s)[1:]:
        oid = attr(node, "ObjectiveID")
        if oid:
            objectives[oid] = {
                "quest": attr(node, "QuestID"),
                "desc": attr(node, "Description"),
                "markers": re.findall(r'id="Markers" type="FixedString" value="([^"]*)"', node),
                # story order within a quest (1000, 1100, ... COMPLETION 1000000): the current objective is the
                # unlocked step's with the highest; the step list in quest_prototypes.lsx is not in unlock order
                "priority": attr(node, "Priority") or "0",
            }
    with open(out, "w", encoding="utf-8") as o:
        o.write("-- GENERATED by tools/vis/gen_marker_index.py from the game's Story/Journal files.\n")
        o.write("-- Do not edit by hand; regenerate after game patches.\n")
        o.write("return {\nmarkers = {\n")
        for mid in sorted(markers):
            m = markers[mid]
            o.write("  [%s] = { type = %s, uuid = %s, text = %s, level = %s, icon = %s, radius = %s },\n" % (
                lua_str(mid), lua_str(m["type"]), lua_str(m["uuid"]), lua_str(m["text"]),
                lua_str(m["level"]), lua_str(m["icon"]), m["radius"]))
        o.write("},\nobjectives = {\n")
        for oid in sorted(objectives):
            ob = objectives[oid]
            o.write("  [%s] = { quest = %s, desc = %s, priority = %s, markers = { %s } },\n" % (
                lua_str(oid), lua_str(ob["quest"]), lua_str(ob["desc"]), int(ob["priority"]),
                ", ".join(lua_str(x) for x in ob["markers"])))
        o.write("},\n}\n")
    print("markers", len(markers), "objectives", len(objectives))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
