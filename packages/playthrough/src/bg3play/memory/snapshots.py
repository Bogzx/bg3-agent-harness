#!/usr/bin/env python3
"""Regenerate memory/snapshots/*.md from LIVE, player-visible game state.

    python3 tools/memory/snapshots.py --memory-dir play/memory
    uv run --project bridge python tools/memory/snapshots.py --memory-dir play/memory   (same thing)

Writes status.md, party.md, inventory.md, journal.md and map.md using the bridge's RPC client
(bridge/src/bg3ai/game.py) and compact renderer (render.py). Both are stdlib-only, so plain python3 works.
Best effort by design: ops the mod doesn't implement (yet) are skipped, and their previous file is left
alone. If the game isn't reachable, nothing is written. Exit status is always 0 unless --strict is given.

Snapshots have no entity handles: e12-style ids only mean something inside one MCP server process,
so here entities are referred to by display name only.
"""

from __future__ import annotations

import argparse
import importlib
import json
import re
import socket
import sys
import time
from collections.abc import Callable
from pathlib import Path
from typing import Any, cast

from bg3play.jsontypes import Obj, is_list, is_obj
from bg3play.memory import memlib

DEBUG_HOST = "127.0.0.1"
SNAP_FILES = ("status", "party", "inventory", "journal", "map", "gear")


def _render() -> Any:
    return importlib.import_module("bg3ai.render")  # the bridge ships no types


def make_handles():
    """A Handles that renders entities by name only (no per-process e12 ids, never GUIDs)."""
    render = _render()

    class NameOnlyHandles(render.Handles):
        def get(self, uuid: str, name: str | None = None) -> str:
            return ""

    return NameOnlyHandles()


_SPACES = re.compile(r"[ \t]{2,}")


def tidy(text: str) -> str:
    """Collapse the gaps left by blank handles; drop trailing spaces and empty bullets."""
    out: list[str] = []
    for line in text.splitlines():
        indent = line[: len(line) - len(line.lstrip())]
        line = indent + _SPACES.sub(" ", line.lstrip()).rstrip()
        line = re.sub(r"^(\s*-) +", r"\1 ", line)
        line = line.replace("*  ", "*").replace("{ ", "{").replace("[ ", "[")
        if line.strip() in ("-", ""):
            if out and out[-1] == "":
                continue
            line = ""
        out.append(line)
    return "\n".join(out).strip() + "\n"


def header(kind: str, session: str | None, now: float | None = None) -> str:
    ts = time.strftime("%Y-%m-%d %H:%M", time.localtime(now or time.time()))
    return (
        f"<!-- generated by bg3ai snapshots.py {ts} session {session or '?'}; do not edit -->\n"
        f"# Snapshot: {kind} ({ts}, {session or 'no session'})\n\n"
    )


# ---------------------------------------------------------------- renderers (pure)


def _class_str(c: Any) -> str:
    """{'class': 'Cleric', 'subclass': 'Trickery Domain', 'level': 6} -> 'Cleric 6 (Trickery Domain)'."""
    if not is_obj(c):
        return str(c)
    name = c.get("class") or c.get("name") or "?"
    s = f"{name} {c['level']}" if c.get("level") else str(name)
    return s + (f" ({c['subclass']})" if c.get("subclass") else "")


def _normalize_member(m: dict[str, Any]) -> dict[str, Any]:
    m = dict(m)
    if is_list(m.get("classes")):
        m["classes"] = [_class_str(c) for c in m["classes"]]
    return m


def render_status(st: dict[str, Any]) -> str:
    r = _render()
    st = dict(st)
    st["party"] = [_normalize_member(m) if is_obj(m) else m for m in st.get("party") or ()]
    return tidy(r.render_status(st, None, make_handles()))


SHEET_ORDER = [
    "classes",
    "level",
    "race",
    "ac",
    "hp",
    "max_hp",
    "abilities",
    "saves",
    "skills",
    "resources",
    "concentration",
    "conditions",
    "statuses",
    "equipment",
    "passives",
    "features",
    "resistances",
    "xp",
]
SHEET_SKIP = {"name", "uuid", "pos"}


def render_sheet(sheet: Any) -> str:
    """One `- key: value` line per top-level field, most useful fields first."""
    r = _render()
    handles = make_handles()
    if not is_obj(sheet):
        return r.compact(sheet, handles) if not isinstance(sheet, str) else sheet
    keys = [k for k in SHEET_ORDER if k in sheet] + [k for k in sheet if k not in SHEET_ORDER]
    lines: list[str] = []
    for k in keys:
        v = sheet[k]
        if k in SHEET_SKIP or v in (None, [], {}, False):
            continue
        if k == "classes" and is_list(v):
            v = ", ".join(_class_str(c) for c in v)
        elif k in ("statuses", "conditions", "passives", "features") and is_list(v):
            v = ", ".join(str(x.get("name") or "?") if is_obj(x) else str(x) for x in v)
        lines.append(f"- {k}: {r.compact(v, handles, 1) if isinstance(v, (dict, list)) else r.compact(v, handles)}")
    return "\n".join(lines)


def render_party(sheets: list[tuple[str, Any]]) -> str:
    parts = [f"## {name}\n{render_sheet(sheet)}\n" for name, sheet in sheets]
    return tidy("\n".join(parts)) if parts else "No party data.\n"


COSMETIC_SLOTS = ("Underwear", "Vanity")


def item_line(it: dict[str, Any]) -> str:
    name = str(it.get("name", "?"))
    bits = [name + (f" x{it['count']}" if it.get("count", 1) not in (1, None) else "")]
    if it.get("rarity") and it["rarity"] not in ("common", "Common"):
        bits.append(f"({it['rarity']})")
    if it.get("equipped_slot"):
        bits.append(f"[equipped {it['equipped_slot']}]")
    if it.get("in"):
        bits.append(f"in {it['in']}")
    for flag in ("story", "unique", "usable"):
        if it.get(flag) is True:
            bits.append(flag)
    return "- " + " ".join(bits)


def render_inventory(inv: Any, names: dict[str, str] | None = None) -> str:
    """Group items by owner; `names` maps owner uuids to display names (from state.status)."""
    r = _render()
    handles = make_handles()
    items = inv.get("items") if is_obj(inv) and "items" in inv else inv
    if is_list(items):
        by_owner: dict[str, list[str]] = {}
        for it in items:
            if not is_obj(it):
                continue
            if str(it.get("equipped_slot", "")).startswith(COSMETIC_SLOTS):
                continue
            owner = str(it.get("owner_name") or it.get("owner") or "?")
            owner = (names or {}).get(owner.lower(), owner)
            if memlib.UUID_LIKE.search(owner):
                owner = "other"
            by_owner.setdefault(owner, []).append(handles.scrub(item_line(it)))
        if by_owner:
            return tidy("\n".join(f"## {o}\n" + "\n".join(lines) + "\n" for o, lines in by_owner.items()))
        return "Inventory is empty.\n"
    return tidy(r.compact(inv, handles))


def render_gear(inv: Any, names: dict[str, str] | None = None) -> str:
    """Between-session gear check (S026: Sentinel Shield left in a bag, Gale in a Simple Robe at L5, bags of
    junk, supplies short): better gear per member, junk to sell, supplies. Injected at the next session start
    (session.py) so the agent equips it first thing (equip_best)."""
    economy: Any = importlib.import_module("bg3ai.economy")

    if not is_obj(inv) or "items" not in inv:
        return ""

    def owner(u: Any) -> str:
        return (names or {}).get(str(u).lower(), "other")

    lines = economy.gear_report(inv, owner)

    if not lines:
        return "## Gear check\n- nothing to change\n"
    return "## Gear check (equip_best equips the upgrades; trade sell=junk at a trader)\n" + "\n".join(lines) + "\n"


JOURNAL_STEPS = 3


def render_journal(j: Any) -> str:
    r = _render()
    quests = j.get("quests") if is_obj(j) and "quests" in j else j
    if is_list(quests):
        active: list[str] = []
        done: list[str] = []
        for q in quests:
            if not is_obj(q):
                continue
            title = q.get("title", "?")
            cat = f" ({q['category']})" if q.get("category") else ""
            if q.get("done"):
                done.append(f"- {title}{cat}")
                continue
            all_steps: list[Any] = q.get("steps") or []
            shown = all_steps[-JOURNAL_STEPS:]
            more = (
                f"\n  - (+{len(all_steps) - len(shown)} earlier entries; get_journal has them)"
                if len(all_steps) > len(shown)
                else ""
            )
            active.append(f"- {title}{cat}{more}" + "".join(f"\n  - {s}" for s in shown))
        out = "## Active\n" + ("\n".join(active) or "(none)") + "\n\n## Done\n" + ("\n".join(done) or "(none)")
        return tidy(out)
    return tidy(r.compact(j, make_handles()))


def render_map(m: Any) -> str:
    r = _render()
    if is_obj(m):
        where = " · ".join(str(m[k]) for k in ("region", "subregion", "level") if m.get(k))
        wps: list[Any] = m.get("waypoints") or []
        lines = [f"Current: {where or '?'}", "", "## Unlocked waypoints"]
        lines += [f"- {w.get('name', '?') if is_obj(w) else w}" for w in wps] or ["(none)"]
        rest = {k: v for k, v in m.items() if k not in ("region", "subregion", "level", "waypoints")}
        if rest:
            lines += ["", "## Other", r.compact(rest, make_handles())]
        return tidy("\n".join(lines))
    return tidy(r.compact(m, make_handles()))


# ---------------------------------------------------------------- live collection


def port_open(port: int, timeout: float = 1.0) -> bool:
    try:
        with socket.create_connection((DEBUG_HOST, port), timeout=timeout):
            return True
    except OSError:
        return False


def collect(rpc: Callable[..., Any], ops: set[str]) -> tuple[dict[str, str], list[str]]:
    """Run the state ops that exist; return ({file: markdown}, [notes]). `rpc(op, args)` may raise."""
    out: dict[str, str] = {}
    notes: list[str] = []

    def call(op: str, args: dict[str, Any] | None = None) -> Any:
        if op not in ops:
            raise LookupError(f"{op} not implemented by the mod yet")
        return rpc(op, args or {})

    status = None
    try:
        status = call("state.status")
        out["status"] = render_status(status)
    except Exception as e:
        notes.append(f"status: skipped ({e})")

    if status and is_list(status.get("party")):
        sheets: list[tuple[Any, Any]] = []
        for member in status["party"]:
            name = member.get("name", "?")
            try:
                sheets.append((name, call("state.character", {"uuid": member.get("uuid")})))
            except LookupError as e:
                notes.append(f"party: skipped ({e})")
                sheets = []
                break
            except Exception as e:
                sheets.append((name, f"(unavailable: {e})"))
        if sheets:
            out["party"] = render_party(sheets)
    else:
        notes.append("party: skipped (no party list in state.status)")

    names: dict[str, str] = {}
    for member in cast(Obj, status or {}).get("party") or ():
        if is_obj(member) and member.get("uuid"):
            names[str(member["uuid"]).lower()] = member.get("name", "?")

    def inventory(inv: Any) -> str:
        gear = render_gear(inv, names)
        if gear:
            out["gear"] = tidy(gear)
        return render_inventory(inv, names)

    for key, op, fn in (
        ("inventory", "state.inventory", inventory),
        ("journal", "state.journal", render_journal),
        ("map", "state.map", render_map),
    ):
        try:
            out[key] = fn(call(op))
        except Exception as e:
            notes.append(f"{key}: skipped ({e})")
    return out, notes


def write_snapshots(mem: Path, docs: dict[str, str], session: str | None, now: float | None = None) -> list[str]:
    d = mem / "snapshots"
    d.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    for key, body in docs.items():
        p = d / f"{key}.md"
        tmp = p.with_suffix(".tmp")
        tmp.write_text(header(key, session, now) + body)
        tmp.replace(p)
        written.append(p.name)
    return written


def current_session(mem: Path) -> str | None:
    st = memlib.load_state(mem)
    return memlib.session_id(st["current"]) if st.get("current") else None


def run(mem: Path, port: int = 9998) -> tuple[list[str], list[str]]:
    """Generate snapshots from the live game. Returns (files written, notes). Never raises for game trouble."""
    if not mem.is_dir():
        return [], [f"memory dir {mem} does not exist"]
    if not port_open(port):
        return [], [f"game not reachable on {DEBUG_HOST}:{port}; snapshots left as they were"]
    try:
        from bg3ai.game import Game, GameError  # pyright: ignore[reportMissingTypeStubs]
    except ImportError as e:
        return [], [f"bridge (bg3ai) not importable: {e}"]
    game: Any = Game(port=port)
    try:
        info = game.rpc("sys.info", context="server", timeout=5.0)
        ops = set(info.get("ops") or [])
    except GameError as e:
        return [], [f"server context not ready ({e}); snapshots left as they were"]
    try:

        def rpc(op: str, args: Any) -> Any:
            return game.rpc(op, args, "server", timeout=8.0)

        docs, notes = collect(rpc, ops)

    finally:
        game.close()
    return write_snapshots(mem, docs, current_session(mem)), notes


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--memory-dir")
    ap.add_argument("--port", type=int, default=int(__import__("os").environ.get("BG3LE_DEBUG_PORT", "9998")))
    ap.add_argument("--json", action="store_true", help="print a JSON summary")
    ap.add_argument("--strict", action="store_true", help="exit 1 if nothing was written")
    args = ap.parse_args(argv)
    mem = memlib.resolve_memory_dir(args.memory_dir)
    written, notes = run(mem, args.port)
    if args.json:
        print(json.dumps({"written": written, "notes": notes}))
    else:
        print(f"snapshots: wrote {', '.join(written) if written else 'nothing'}")
        for n in notes:
            print(f"  {n}")
    return 1 if args.strict and not written else 0


if __name__ == "__main__":
    sys.exit(main())
