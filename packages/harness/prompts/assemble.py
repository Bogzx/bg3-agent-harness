"""The agent's system text, assembled from data files (D3 in docs/OVERHAUL-PLAN.md; research/arch/bench.md §2.6).

    rules/*.md                 how the game, the tools, fairness and the clock line work: what every model is told
    rules/capabilities/*.md    the same for one tool group (bridge capabilities.py GROUPS), only when it is on
    coaching/*.md              how to play well and the playthrough's own protocol (memory files, sessions)
    clients/<client>.md        what one client truly needs on top (claude: Claude Code's mcp__bg3__ names and
                               ToolSearch); other clients get none

A rule says how something works or what is fair; coaching says how to play well, or exists because a session went
wrong. Session anecdotes stay out of both (tests/test_prompts.py lints it).

    assemble("rules")                       -> Assembly(text, sha256, parts)   the harness default (rules only)
    assemble("rules+coaching", "claude")    -> what play/CLAUDE.md holds (generated, see main())

The text is byte-stable: the same files give the same bytes and hash (the prompt-cache prefix, the run manifest's
prompt.sha256 and parts). Standard library only: the bridge loads this file by path.

    python3 packages/harness/prompts/assemble.py rules+coaching --client claude --out play/CLAUDE.md [--check]
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path
from typing import NamedTuple

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
CLAUDE_MD = REPO / "play" / "CLAUDE.md"

RULES = ("rules/core.md", "rules/game-and-tools.md", "rules/fairness.md", "rules/clock.md")
# The tool groups of bridge/src/bg3ai/capabilities.py (BG3AI_TOOLS): a group's rules file, and the tools a rules
# text may name only when that group is on. "reload" has no rules file: nothing in the rules mentions reloading.
CAPABILITIES: dict[str, tuple[str, ...]] = {
    "memory": (
        "memory_list",
        "memory_read",
        "memory_search",
        "memory_write",
        "memory_edit",
        "memory_append",
        "note",
        "session_start",
        "end_session",
        "recall",
    ),
    "wiki": ("wiki_search", "wiki_page"),
    "reload": ("load_game",),
    "saves": ("save_game", "list_saves"),
    "screenshots": ("screenshot", "zoom"),
    "raw_input": ("press_key", "click", "ui_dump"),
}
ALL_CAPS = frozenset(CAPABILITIES)
COACHING = (
    "coaching/mission.md",
    "coaching/pace.md",
    "coaching/efficiency.md",
    "coaching/reflexes.md",
    "coaching/core-loop.md",
    "coaching/playbooks.md",
    "coaching/memory-protocol.md",
    "coaching/saves.md",
    "coaching/stuck.md",
    "coaching/session-lifecycle.md",
    "coaching/style.md",
)
CONDITIONS = {"rules": (), "rules+coaching": COACHING}
CLIENTS = ("mcp", "claude", "codex", "gemini", "pi")  # only claude has an appendix (clients/claude.md)
# The kickoff's pace pre-flight (runner/play.py PACE_PREFLIGHT): coaching, so only in a coaching condition's kickoff.
PACE_PREFLIGHT = "coaching/pace-preflight.md"
GENERATED_HEADER = (
    "<!-- Generated by packages/harness/prompts/assemble.py from packages/harness/prompts "
    "(rules+coaching, client claude). Edit those files, then run: python3 "
    "packages/harness/prompts/assemble.py rules+coaching --client claude --out play/CLAUDE.md -->\n\n"
)


class Assembly(NamedTuple):
    text: str
    sha256: str
    parts: list[dict[str, str]]  # [{"file": "rules/core.md", "sha256": ...}] in order (the manifest's prompt.parts)


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def part_files(condition: str = "rules", client: str = "mcp", caps: frozenset[str] | set[str] = ALL_CAPS) -> list[str]:
    """The files of a condition, in order: rules, the on groups' rules, the client's appendix, then coaching."""
    if condition not in CONDITIONS:
        raise ValueError(f"unknown condition {condition!r} (one of {', '.join(CONDITIONS)})")
    if client not in CLIENTS:
        raise ValueError(f"unknown client {client!r} (one of {', '.join(CLIENTS)})")
    if unknown := sorted(set(caps) - ALL_CAPS):
        raise ValueError(f"unknown capability {', '.join(unknown)} (one of {', '.join(CAPABILITIES)})")
    if CONDITIONS[condition] and frozenset(caps) != ALL_CAPS:
        # the coaching is the playthrough's: it names the memory files, the wiki, saves and reloads throughout
        raise ValueError(f"{condition} needs every capability on (off: {', '.join(sorted(ALL_CAPS - set(caps)))})")
    files = list(RULES) + [f"rules/capabilities/{c}.md" for c in CAPABILITIES if c in caps and c != "reload"]
    if (HERE / "clients" / f"{client}.md").exists():
        files.append(f"clients/{client}.md")
    return files + list(CONDITIONS[condition])


def assemble(
    condition: str = "rules", client: str = "mcp", caps: frozenset[str] | set[str] = ALL_CAPS, root: Path = HERE
) -> Assembly:
    """The system text of a condition for a client: its parts joined by a blank line, trailing newline."""
    parts: list[dict[str, str]] = []
    texts: list[str] = []
    for f in part_files(condition, client, caps):
        data = (root / f).read_bytes()
        parts.append({"file": f, "sha256": _sha(data)})
        texts.append(data.decode("utf-8").strip())
    text = "\n\n".join(texts) + "\n"
    return Assembly(text, _sha(text.encode("utf-8")), parts)


def allowlist(tools: list[str] | set[str], caps: frozenset[str] | set[str] = ALL_CAPS) -> set[str]:
    """The tools a condition exposes: the server's tools minus the groups that are off."""
    return set(tools) - {t for c, names in CAPABILITIES.items() if c not in caps for t in names}


def pace_preflight(client: str = "mcp", root: Path = HERE) -> str:
    """The kickoff's pace pre-flight; Claude Code's gets the tool-name line (clients/claude-kickoff.md) first."""
    head, _, rest = (root / PACE_PREFLIGHT).read_text(encoding="utf-8").strip().partition("\n")
    extra = root / "clients" / f"{client}-kickoff.md"
    return "\n".join([head, *([extra.read_text(encoding="utf-8").strip()] if extra.exists() else []), rest])


def claude_md() -> str:
    """play/CLAUDE.md's content: Claude Code reads it by itself in play/."""
    return GENERATED_HEADER + assemble("rules+coaching", "claude").text


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    ap.add_argument("condition", choices=list(CONDITIONS))
    ap.add_argument("--client", default="mcp", choices=list(CLIENTS))
    ap.add_argument("--out", type=Path, help="write the text here (play/CLAUDE.md gets the generated header)")
    ap.add_argument("--check", action="store_true", help="exit 1 when --out differs instead of writing it")
    a = ap.parse_args(argv)
    got = assemble(a.condition, a.client)
    text = got.text
    if a.out and a.out.resolve() == CLAUDE_MD:
        if (a.condition, a.client) != ("rules+coaching", "claude"):
            ap.error("play/CLAUDE.md is the rules+coaching text for the claude client")
        text = claude_md()
    if not a.out:
        sys.stdout.write(text)
        return 0
    if a.check:
        same = a.out.exists() and a.out.read_text(encoding="utf-8") == text
        print(f"{a.out}: {'up to date' if same else 'differs: regenerate it'}")
        return 0 if same else 1
    a.out.write_text(text, encoding="utf-8")
    print(f"{a.out}: {got.sha256[:12]} ({len(got.parts)} parts, {len(text)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
